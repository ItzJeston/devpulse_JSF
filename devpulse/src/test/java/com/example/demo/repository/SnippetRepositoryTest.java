    // 3. TIER 4: REAL-WORLD PERSISTENCE WORKFLOW
    // =========================================================================
    @Nested
    @DisplayName("Tier 4: Real-World Academic Workflows")
    class AcademicWorkflowTests {

        @Test
        @DisplayName("Exp 4 & 5 [Tier 4]: Full academic submission, review mutation, revision cycle")
        void testAcademicPersistenceLifecycleScenario() {
            // Step 1: Student submits initial code
            Snippet initial = createSampleSnippet(
                "NNM24CS107", "Jeston Correa", "jeston@nmamit.in", 4,
                "Java", "QuickSort Algorithm",
                "public void sort(int[] arr) { /* incomplete */ }",
                "public void sort(int[] arr) { /* incomplete */ }",
                "PENDING", "", 0
            );
            Snippet saved = snippetRepository.save(initial);
            Long id = saved.getId();
            entityManager.flush();
            entityManager.clear();

            // Step 2: Faculty reviewer evaluates and requests revision
            Snippet reviewStage = snippetRepository.findById(id).orElseThrow();
            reviewStage.setStatus("NEEDS_REVISION");
            reviewStage.setReviewerComments("Missing partition logic. Please complete and resubmit.");
            reviewStage.setMarks(4);
            snippetRepository.save(reviewStage);
            entityManager.flush();
            entityManager.clear();

            // Step 3: Student resubmits revised implementation
            Snippet revisionStage = snippetRepository.findById(id).orElseThrow();
            assertEquals("NEEDS_REVISION", revisionStage.getStatus());
            assertEquals(4, revisionStage.getMarks());
            revisionStage.setRawCode("public void sort(int[] arr) { partition(arr, 0, arr.length - 1); }");
            revisionStage.setSanitizedCode("public void sort(int[] arr) { partition(arr, 0, arr.length - 1); }");
            snippetRepository.save(revisionStage);
            entityManager.flush();
            entityManager.clear();

            // Step 4: Reviewer gives final approval
            Snippet finalStage = snippetRepository.findById(id).orElseThrow();
            finalStage.setStatus("APPROVED");
            finalStage.setReviewerComments("Partition verified. Full marks awarded.");
            finalStage.setMarks(10);
            snippetRepository.save(finalStage);
            entityManager.flush();
            entityManager.clear();

            // Verification
            Snippet completed = snippetRepository.findById(id).orElseThrow();
            assertEquals("APPROVED", completed.getStatus());
            assertEquals(10, completed.getMarks());
            assertEquals("Partition verified. Full marks awarded.", completed.getReviewerComments());
            assertTrue(completed.getRawCode().contains("partition(arr"));
        }
    }
